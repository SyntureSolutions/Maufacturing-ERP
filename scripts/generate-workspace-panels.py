"""Generate the CSS that turns older screens' solid-colour / dark cards and banners into white workspace panels.

Prints the block that sits in app/globals.css between the "(generated)" comment and "Older forms and dialogs".
Usage: python scripts/generate-workspace-panels.py > panels.css, then paste it over that block.
"""
TONES = {
    'negative': ['rose', 'red'],
    'positive': ['emerald', 'green', 'teal'],
    'info': ['indigo', 'violet', 'purple', 'blue', 'sky', 'cyan', 'fuchsia', 'pink', 'amber'],
    'critical': ['orange', 'yellow'],
}
SHADES = ['500', '600', '700', '800', '900']
DARK = ['bg-slate-800', 'bg-slate-900', 'bg-slate-950', 'bg-gray-800', 'bg-gray-900', 'bg-gray-950', 'bg-black']
ACCENT = {'negative': 'var(--erp-negative)', 'positive': 'var(--erp-positive)', 'info': 'var(--erp-accent)', 'critical': 'var(--erp-critical)'}
TEXT = {  # light tints meant for dark backgrounds -> readable on white
    'negative': ['rose', 'red'], 'positive': ['emerald', 'green', 'teal'],
    'info': ['indigo', 'violet', 'purple', 'blue', 'sky', 'cyan', 'fuchsia', 'pink', 'amber'], 'critical': ['orange', 'yellow', 'lime'],
}
TEXT_COLOR = {'negative': 'var(--erp-negative)', 'positive': 'var(--erp-positive)', 'info': 'var(--erp-accent)', 'critical': '#b55a00'}

# padded block containers only: status dots, progress bars, icon chips and pills keep their colour
PADDED = ':is([class^="p-"], [class*=" p-"], [class^="px-"], [class*=" px-"], [class^="py-"], [class*=" py-"])'
BLOCK = f':is(div, section, article, header){PADDED}:not([class*="rounded-full"]):not([class*="fixed"])'


def bg_tokens(names):
    return [f'[class~="{n}"]' for n in names]


solid = {tone: bg_tokens([f'bg-{c}-{s}' for c in colors for s in SHADES]) for tone, colors in TONES.items()}
dark = bg_tokens(DARK) + ['[class*="bg-gradient-to-"]']
all_tokens = dark + [t for ts in solid.values() for t in ts]
panel = f'.erp-main {BLOCK}:is({", ".join(all_tokens)})'

out = ['/* Older screens: solid-colour KPI cards and dark banners become white workspace panels (generated by scripts/generate-workspace-panels.py; edit the script, not these lines). */']
out.append(f'{panel} {{ background: #fff; background-image: none; color: var(--erp-ink); border: 0; border-radius: .25rem; box-shadow: var(--erp-panel-shadow); }}')
for tone, ts in solid.items():
    out.append(f'.erp-main {BLOCK}:is({", ".join(ts)}) {{ box-shadow: inset 4px 0 {ACCENT[tone]}, var(--erp-panel-shadow); }}')
# text inside (and on) a converted panel
# ...but not text on its own solid background (badges, buttons) or inside a button/link, which stays white
within = f'{panel} :is(.text-white, [class*="text-white/"], .text-slate-50, .text-slate-100):not([class*="bg-"]):not(button *):not(a *):not(button):not(a)'
self_text = f'{panel}:is(.text-white, [class*="text-white/"])'
out.append(f'{within}, {self_text} {{ color: var(--erp-ink); }}')
out.append(f'{panel} :is(.text-slate-200, .text-slate-300, .text-slate-400, .text-gray-300, .text-gray-400) {{ color: var(--erp-muted); }}')
for tone, colors in TEXT.items():
    sel = ', '.join(f'.text-{c}-{s}' for c in colors for s in ['100', '200', '300', '400'])
    out.append(f'{panel} :is({sel}) {{ color: {TEXT_COLOR[tone]}; }}')
# translucent white chips and rules inside become light grey
out.append(f'{panel} [class*="bg-white/"] {{ background-color: #f2f2f2; }}')
out.append(f'{panel} [class*="border-white/"], {panel} :is(.border-slate-700, .border-slate-800) {{ border-color: var(--erp-line); }}')
out.append(f'{panel} :is(.divide-white\\/10, .divide-slate-700) > * + * {{ border-color: var(--erp-line); }}')
# buttons: dark and saturated blue/purple fills become the emphasized blue; no heavy drop shadows on buttons
BTN = ', '.join(bg_tokens(DARK) + bg_tokens([f'bg-{c}-{s}' for c in TONES['info'] for s in SHADES]))
out.append(f'.erp-main :is(button, a):is({BTN}) {{ background-color: var(--erp-accent); border-color: var(--erp-accent); color: #fff; }}')
out.append(f'.erp-main :is(button, a):is({BTN}):hover:not(:disabled) {{ background-color: var(--erp-accent-hover); }}')
out.append(f'.erp-main :is(button, a):is({BTN}) svg {{ color: #fff; }}')
# tinted text inside a button that is now blue (e.g. a selected card) stays readable
out.append(f'.erp-main :is(button, a):is({BTN}) :is([class*="text-blue-"], [class*="text-indigo-"], [class*="text-sky-"], [class*="text-slate-"], [class*="text-amber-"], [class*="text-violet-"]) {{ color: rgba(255, 255, 255, .85); }}')
out.append('.erp-main :is(button, a):is([class*="shadow-lg"], [class*="shadow-md"], [class*="shadow-xl"]) { box-shadow: none; }')
print('\n'.join(out))
